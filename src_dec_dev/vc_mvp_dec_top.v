    parameter VC_EN_BI_DIR = 0,
    parameter VC_PIC_X_NB  = 12,
    parameter VC_PIC_Y_NB  = 12,
    parameter MRG2MC_DW    = VC_PIC_X_NB + VC_PIC_Y_NB + 39
