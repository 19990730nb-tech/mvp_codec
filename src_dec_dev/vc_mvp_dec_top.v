    input                           ref2irpu_rd_lat,
    input      [32:0]               ref2irpu_rd,

    input      [2:0]                mc2mrg_cand_ack,
    output     [2:0]                dec_mrg2mc_cand_rdy,
    output     [2:0][MRG2MC_DW-1:0] dec_mrg2mc_cand_data,
    output     [2:0]                dec_mrg2mc_cand_nb,
    output     [2:0]                dec_mrg2mc_cand_done,

