    output                          cand_capture_done,
    output                          cand_busy,
    output     [31:0]               dec_spatial_mvp,
    output                          dec_recon_start,
    output                          recon_done,
    output                          dec_send,
    output                          mc_commit,
    output     [31:0]               dec_final_mv,
    output     [3:0]                dec_final_ref_idx,
    output     [1:0][15:0]          dec_mvd,
    output     [3:0]                dec_ref_idx,
    output                          dec_is_skip,
    output                          dec_part_mode,
    output     [1:0]                dec_sub_idx,
    output     [2:0]                dec_cux,
    output     [2:0]                dec_cuy,
